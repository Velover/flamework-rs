//! Flamework's TypeScript transformer (`@flamework-experimental/transformer`, v2) ported to Rust, as a plugin compiled
//! into rbxts-rs, roblox-ts in Rust (DESIGN §10). A project built with it gets what roblox-ts with the TS transformer
//! writes: the Luau, `flamework.build` and the include JSON (`include/flamework`), byte for byte except where the
//! repository's README says otherwise (see [Parity and limitations](#parity-and-limitations)).
//!
//! `DESIGN §n` references here and in the other crates are to rbxts-rs's design document, which this repository
//! does not hold. Each module's docs name the TS transformer files it ports (paths under the transformer package's
//! `src`, such as `util/functions/buildGuardFromType.ts`).
//!
//! # Using it
//!
//! [`Flamework`] is the plugin (an `rbxts_plugin::Plugin`). The `rbxtsc-fw` binary (the `rbxtsc_fw` crate) is the
//! rbxtsc command line with it registered, and nothing else:
//!
//! ```ignore
//! rbxts_cli::Cli::new().plugin(flamework_rs::Flamework::new()).run()
//! ```
//!
//! The plugin is on for a project whose tsconfig lists `@flamework-experimental/transformer` in
//! `compilerOptions.plugins`, and off otherwise. A build with user macro types (the Rust side of
//! `@flamework-experimental/transformer-plugin`) registers them with [`Flamework::macro_type`] in its own `main`; see
//! [`macro_type`].
//!
//! The plugin's API is [`Flamework`], the macro type API ([`MacroType`], [`MacroCx`] and the types its queries
//! return), [`VERSION`], [`ProjectError`] and [`packages`]. [`FwShared`], [`FwState`], [`FwInstance`] and
//! [`FwFilePart`] are the plugin's associated types, public because its `Plugin` impl names them; their contents are
//! internal.
//!
//! # Libraries
//!
//! The parts that need no compiler are public modules:
//! - [`config`]: `flamework.config.json` (find, read, substitute the environment, coerce, validate) and the tsconfig
//!   entry check, with the TS transformer's error texts;
//! - [`env`](mod@env): `.env` / `.env.local` loading and the `${NAME:-fallback}` substitution;
//! - [`build_info`]: `flamework.build` read and write (byte for byte), package build-info discovery, the version
//!   checks;
//! - [`ids`]: the `full` / `short` / `tiny` / `obfuscated` id rules, late-bound in transform order (roblox-ts's
//!   `getChangedFilePaths` order, §10.4);
//! - [`inputs`]: reading the transformer's own files and variables as recorded build inputs;
//! - the byte-exact libraries (§10.5): [`hashids`], [`uuid`], [`sha`], [`glob`], [`node_path`] (Node's `path`), plus
//!   [`json`] (JavaScript's `JSON.parse` / `JSON.stringify` with its property order) and [`jsonc`] (TypeScript's
//!   JSON-with-comments reader, as `ts.parseConfigFileTextToJson` reads a config file).
//!
//! [`hashids`], [`uuid`], [`sha`] and [`glob`] have table-driven parity tests against the node libraries, and [`json`]
//! / [`jsonc`] are checked through the config and build-info tables (`tests/data`, generated by
//! `tests/data/gen/generate.cjs`); [`node_path`] has unit tests.
//!
//! # The plugin
//!
//! The rest is private to the crate; each module's docs say what it does and which TS code it ports:
//! - `plugin`: the `Plugin` / `PluginInstance` impls, the hooks Flamework takes and where each one goes;
//! - `setup`: [`FwShared`] from the package, config, env and build infos, with the version check, reusing the last
//!   committed `flamework.build` ([`FwState`]) in every build but a clean one;
//! - `metadata`: JSDoc `@metadata` requests with `{@link}` entries;
//! - `uid`: type and declaration ids, late in `short` / `tiny` / `obfuscated` mode;
//! - `class_hook`: `Reflect.defineMetadata` at the static-block position, and the decorator checks;
//! - `macros`: user macros: every marker kind, the intrinsics, and the parameter intrinsics;
//! - `guards`: `t` guards from types, for class metadata, `Generic<T, "guard">` and `tuple-guards`;
//! - `serializer`: the serializer generator (`createSerializer`, networking's packed members);
//! - `components`: component config, instance shapes, attribute setters and key obfuscation;
//! - `networking`: call sites on networking members, network decoders, middleware names and the removed-marker
//!   message;
//! - `finish`: id assignment in transform order, `flamework.build`, the include JSON, the glob and path warnings
//!   (with `place_source`, what the place holds at a path);
//! - `part_codec`: [`FwFilePart`] as bytes, for the compiler's incremental state;
//! - `order`, `ts_names`: the order the TS transformer met things in a file, and the names its printer gave
//!   generated locals;
//! - `renamed`: TypeScript's errors for names renamed or removed before beta, naming the replacement;
//! - `schema` (the config schemas, validated as Ajv does), `shuffle` (seeded obfuscation shuffles), `random`, `js`
//!   (JavaScript semantics the TS code relies on).
//!
//! Clean, incremental and watch builds: an incremental build and a watch rebuild reuse the last `flamework.build` (its
//! ids, salt and seeds), and start a new one where the TS transformer refuses changed inputs (`setup`).
//!
//! # Parity and limitations
//!
//! The repository's `README.md` has both. **Parity**: `tools/parity.cjs` builds a whole project with `rbxtsc-fw` and
//! compares its output, file by file and byte for byte, with a TypeScript 5 roblox-ts build of the same project.
//! **Known limitations**: where the output may differ from the TS transformer's, where it differs in shape only, where
//! a failing build is reported differently, where it differs on purpose, and what flamework-rs refuses that the TS
//! transformer builds.
